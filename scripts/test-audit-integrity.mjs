import assert from 'node:assert/strict';
import { createAuditEvent } from '../src/domain/auditLog.js';
import { auditStateIntegrity } from '../src/domain/auditIntegrity.js';

const account = { id: 'acc-1', name: 'Principal', initialBalanceCents: 5000 };
const tx = { id: 'tx-1', description: 'Compra', amountCents: 1000, type: 'despesa', status: 'pago', date: '2026-10-20', accountId: 'acc-1', categoryId: 'cat-1', profileType: 'PF' };
const valid = createAuditEvent({ eventId: 'ev-1', timestamp: '2026-10-20T10:00:00.000Z', action: 'transaction_created', entityId: tx.id, profileType: 'PF', after: tx });
let result = auditStateIntegrity({ auditLog: [valid], transactions: [tx], accounts: [account] });
assert.equal(result.ok, true);
assert.equal(result.checkedEvents, 1);
const dup = { ...valid };
result = auditStateIntegrity({ auditLog: [valid, dup], transactions: [tx], accounts: [account] });
assert.ok(result.issues.some(issue => issue.code === 'duplicate_event_id'));
result = auditStateIntegrity({ auditLog: [{ ...valid, timestamp: 'bad' }], transactions: [tx], accounts: [account] });
assert.ok(result.issues.some(issue => issue.code === 'invalid_timestamp'));
result = auditStateIntegrity({ auditLog: [{ ...valid, action: 'made_up' }], transactions: [tx], accounts: [account] });
assert.ok(result.issues.some(issue => issue.code === 'unknown_action'));
result = auditStateIntegrity({ auditLog: [{ ...valid, after: { ...valid.after, amountCents: 500 } }], transactions: [tx], accounts: [account] });
assert.ok(result.issues.some(issue => issue.code === 'snapshot_mismatch'));
result = auditStateIntegrity({ auditLog: [valid], transactions: [], accounts: [account] });
assert.ok(result.issues.some(issue => issue.code === 'audited_transaction_missing'));
const del = createAuditEvent({ eventId: 'ev-del', timestamp: '2026-10-21T10:00:00.000Z', action: 'transaction_deleted', entityId: tx.id, profileType: 'PF', before: tx });
result = auditStateIntegrity({ auditLog: [del], transactions: [tx], accounts: [account] });
assert.ok(result.issues.some(issue => issue.code === 'deleted_transaction_exists'));
const legacy = auditStateIntegrity({ auditLog: [], transactions: [tx], accounts: [account] });
assert.equal(legacy.ok, true);
assert.equal(legacy.legacyTransactionsWithoutAudit, 1);
const badTx = { ...tx, amountCents: 3.5 };
result = auditStateIntegrity({ auditLog: [], transactions: [badTx], accounts: [account] });
assert.ok(result.issues.some(issue => issue.code === 'ledger_issue'));
const importSummary = createAuditEvent({ eventId: 'ev-import', timestamp: '2026-10-21T10:00:00.000Z', action: 'import_reconciliation_summary', entityType: 'import', profileType: 'PF', metadata: { addedCount: 1, settledCount: 0, skippedCount: 2 } });
result = auditStateIntegrity({ auditLog: [importSummary], transactions: [], accounts: [account] });
assert.equal(result.ok, true);
result = auditStateIntegrity({ auditLog: [{ ...importSummary, metadata: { addedCount: -1, settledCount: 0, skippedCount: 0 } }], transactions: [], accounts: [account] });
assert.ok(result.issues.some(issue => issue.code === 'invalid_import_summary'));
const cardPurchase = { ...tx, id: 'tx-card', accountId: 'card-1' };
result = auditStateIntegrity({ auditLog: [], transactions: [cardPurchase], accounts: [account], virtualAccountIds: ['card-1'] });
assert.equal(result.issues.some(issue => issue.message.includes('Conta de origem inexistente')), false);
const unknownProfile = auditStateIntegrity({ auditLog: [{ ...valid, profileType: '?' }], transactions: [tx], accounts: [account] });
assert.ok(unknownProfile.issues.some(issue => issue.code === 'invalid_profile'));
const missingSnapshot = auditStateIntegrity({ auditLog: [{ ...valid, after: null }], transactions: [tx], accounts: [account] });
assert.ok(missingSnapshot.issues.some(issue => issue.code === 'missing_after_snapshot'));
console.log('Audit integrity tests: 15 passed, 0 failed');
