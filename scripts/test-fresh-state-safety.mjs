import assert from 'node:assert/strict';
import { createFreshState, sanitizeState, sanitizeTransaction } from '../src/domain/sanitize.js';
import { migrateData, CURRENT_SCHEMA_VERSION } from '../src/domain/migrations.js';
import { migrateProfileScopedEntities, entitiesForProfile } from '../src/domain/profileIsolation.js';
import { validateStateStructure } from '../src/domain/stateValidation.js';

const raw = createFreshState();
const migrated = migrateData(raw);
const scoped = migrateProfileScopedEntities(migrated);
const validation = validateStateStructure(scoped, { requireCurrentSchema: true });
assert.equal(validation.valid, true, validation.issues.join(' '));
const state = sanitizeState(scoped);
assert.equal(state.version, CURRENT_SCHEMA_VERSION);
assert.equal(state.schemaVersion, CURRENT_SCHEMA_VERSION);
assert.equal(state.transactions.length, 0, 'primeiro uso não pode criar lançamentos fictícios');
assert.equal(state.cards.length, 0, 'primeiro uso não pode criar cartão fictício');
assert.equal(state.accounts.every(account => account.initialBalanceCents === 0), true, 'contas iniciais devem começar em zero');
assert.equal(entitiesForProfile(state.accounts, 'PF').length, 1);
assert.equal(entitiesForProfile(state.accounts, 'PJ').length, 1);
assert.equal(entitiesForProfile(state.categories, 'PF').length, 5);
assert.equal(entitiesForProfile(state.categories, 'PJ').length, 5);
assert.equal(new Set(state.categories.map(category => category.id)).size, state.categories.length, 'IDs de categorias por perfil devem ser únicos');
assert.equal(state.transactions.length + state.cards.length, 0, 'nenhum passivo ou movimento demonstrativo pode aparecer');
const sanitizedNull = sanitizeState(null);
assert.equal(sanitizedNull.transactions.length, 0, 'sanitizar null não pode reintroduzir movimentos demonstrativos');
assert.equal(sanitizedNull.cards.length, 0, 'sanitizar null não pode inventar cartão');
assert.equal(sanitizedNull.accounts.every(account => account.initialBalanceCents === 0), true, 'sanitizar null não pode inventar saldo');
const sanitizedEmpty = sanitizeState({});
assert.equal(sanitizedEmpty.transactions.length, 0, 'estado incompleto não deve recuperar transações de demonstração');
assert.equal(sanitizedEmpty.accounts.length, 0, 'sanitizador não deve inferir contas para estado incompleto');
assert.equal(sanitizedEmpty.categories.every(category => category.profileType === 'PF'), true, 'fallback legado de categorias deve ser explicitamente PF');

const noAccount = sanitizeTransaction({ id: 'tx-no-account', amountCents: 100, type: 'despesa', status: 'pago', date: '2026-10-28', description: 'Sem conta' });
assert.equal(noAccount.accountId, undefined, 'sanitização não pode anexar lançamento a acc-1 por omissão');
assert.equal(noAccount.categoryId, undefined, 'sanitização não pode inventar categoria');
assert.equal(sanitizeTransaction({ amountCents: 100, accountId: 'acc-1' }), null, 'ID ausente não pode ser substituído por aleatório');
assert.equal(sanitizeTransaction({ id: 'fractional-cent', amountCents: 12.5, amount: 99, accountId: 'acc-1' }), null, 'centavos inválidos não podem cair em fallback legado');
assert.equal(sanitizeTransaction({ id: 'negative', amountCents: -1, accountId: 'acc-1' }), null, 'valor negativo não pode ser clamped para zero');
assert.equal(sanitizeTransaction({ id: 'too-precise', amount: 1.239, accountId: 'acc-1' }), null, 'valor legado com precisão além de centavos é recusado');
console.log('Fresh state and sanitizer safety: 23 assertions passed, 0 failed');
